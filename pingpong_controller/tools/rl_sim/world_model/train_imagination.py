def validate_no_update_contract(cfg):
    implementation = cfg['imagination_implementation']
    if (implementation['actor_updates_authorized']
            or implementation['critic_updates_authorized']
            or not implementation['world_model_frozen']
            or implementation['contact_residual_enabled']):
        raise ValueError('This entry point implements the frozen no-update contract only')
    if any(cfg['imagination'][key] != 'imagination' for key in
           ('actor_training_source', 'critic_training_source')):
        raise ValueError('Teacher transitions or returns cannot train this learner')
    if implementation['critic']['hidden_sizes'] != [256, 256]:
        raise ValueError('Unregistered critic architecture')
    return RewardContract(**implementation['reward']['coefficients'])


def distribution(value):
    a = np.asarray(value, dtype=np.float64).ravel()
    if not a.size:
        return dict(count=0)
    if not np.isfinite(a).all():
        raise FloatingPointError('Nonfinite validation statistic')
    return dict(count=a.size, mean=float(a.mean()), minimum=float(a.min()),
        p50=float(np.quantile(a, .5)), p95=float(np.quantile(a, .95)),
        maximum=float(a.max()))


def tree_difference(left, right):
    values = [float(np.max(np.abs(np.asarray(a, dtype=np.float64)
                                 - np.asarray(b, dtype=np.float64))))
              for a, b in zip(jax.tree.leaves(left), jax.tree.leaves(right))]
    return max(values, default=0.)


def gradient_summary(gradient):
    leaves = [np.asarray(x, dtype=np.float64) for x in jax.tree.leaves(gradient)]
    if any(not np.isfinite(x).all() for x in leaves):
        raise FloatingPointError('Nonfinite diagnostic gradient')
    return dict(norm=float(np.sqrt(sum(np.sum(x*x) for x in leaves))),
        maximum=float(max(np.max(np.abs(x)) for x in leaves)),
        nonzero_elements=int(sum(np.count_nonzero(x) for x in leaves)))


def timed(function, *args, **kwargs):
    started = time.monotonic()
    result = function(*args, **kwargs)
    jax.block_until_ready(result)
    return result, time.monotonic() - started


def validate(cfg, args, guard, report):
    reward = validate_no_update_contract(cfg)
    root = repository_root()/cfg['resources']['output_root']
    reader = AuditReader(root/'support_replay_full_a01', guard.budget, max_bytes=0)
    parameters, options, references, auxiliary, auxiliary_reference = load_components(
        cfg, reader,
        robot_checkpoint=root/'support_robot_fit_a02/robot_support_u006144.json',
        contact_checkpoint=root/'contact_activation_control_a01/contact_coupled_u014336.json',
        auxiliary_checkpoint=root/'solver_aux_fit_a01/auxiliary_u004096.json')
    bundle = build_native_environment(cfg, n_envs=1)
    control = ControlContract.from_native(bundle.environment)
    names = list(reader.records)[:2]
    record = reader.records[names[0]]
    within = reader.read(names[0], names={'state__task_within_task_bounds'})[
        'state__task_within_task_bounds'][0]
    eligible = [i for i, group in enumerate(record['record']['groups'])
                if group['split'] == 'validation' and bool(within[i])]
    if len(eligible) < 4:
        raise ValueError('Insufficient task-eligible held-out seeds for the diagnostic')
    # Selection precedes imagined rollout; unsuccessful/missing-event lanes stay.
    lanes = np.asarray(eligible[:32], dtype=np.int32)
    raw, values, _ = read_selected_trial(reader, names, lanes)
    bank, context, checks = teacher_seeds(reader, record, lanes, raw, values,
        options, make_bank_builder(options, control))
    initial = select_teacher_seeds(bank, jnp.zeros(len(lanes), jnp.int32))
    goals = jnp.asarray(values['state__goal_xyz_m'][0])
    state = init_imagined(initial, context, goals)
    layout = critic_layout(initial, state.task, state.events, context, state.episode_steps)
    write_json_unique(args.output_dir/'critic_layout.json', layout, guard.budget)
    actor = expand_actor_history(load_v321_actor(repository_root(), cfg['lineage']['actor_source']))
    critic = init_critic(jax.random.PRNGKey(args.seed), layout['dimension'])
    keys = jax.random.split(jax.random.PRNGKey(args.seed+1), len(lanes))
    session = init_learner(actor, critic, init_pool(state, keys), seed=args.seed+2)
    frozen = dict(actor=actor, critic=critic, target=critic,
        robot=parameters['robot'], auxiliary=auxiliary,
        actor_optimizer=session.actor_optimizer, critic_optimizer=session.critic_optimizer)
    frozen_digest = numeric_tree_digest(frozen)
    options = dict(options, control_contract=control, episode_contract=EpisodeContract.from_config(cfg),
        reward_contract=reward, ar1_enabled=False, exploration_std=cfg['imagination']['exploration_std'])
    proposals = jnp.broadcast_to(goals, (64, len(lanes), 3))
    run = jax.jit(lambda s, k, g: policy_window(actor, parameters['robot'], auxiliary,
        s, k, g, **options))
    report.update(dataset_sha256=reader.identity, references=references,
        auxiliary_reference=auxiliary_reference, seed_checks=checks,
        selected_lanes=lanes.tolist(), eligible_validation_lanes=len(eligible),
        excluded_initially_outside_task_bounds=len([g for g in record['record']['groups']
            if g['split']=='validation'])-len(eligible),
        critic_dimension=layout['dimension'], reward_coefficients=asdict(reward),
        frozen_before_sha256=frozen_digest)
    del bank, raw, values, bundle
    release_cpu_heap()
    guard.check()
    window, first_s = timed(run, state, keys, proposals)
    repeat, warmed_s = timed(run, state, keys, proposals)
    report['forward'] = dict(first_including_compile_s=first_s, warmed_s=warmed_s,
        repeated_max_abs=tree_difference(window, repeat), lanes=len(lanes), horizon=64)
    transition = jax.device_get(window.transitions)
    active = transition.valid.astype(bool)
    report['rollout'] = dict(valid_transitions=int(active.sum()),
        physical_failures=int(transition.terminated.sum()),
        model_truncations=int(transition.model_truncated.sum()),
        time_limits=int(transition.truncated.sum()),
        valid_releases=int(transition.task_events['valid_release'].sum()),
        valid_apexes=int(transition.task_events['valid_apex'].sum()),
        reward_by_transition=distribution(transition.reward[active]),
        reward_by_lane=distribution(transition.reward.sum(axis=0)),
        terms={k:dict(active=distribution(v[active]), lane_sum=distribution(v.sum(axis=0)))
               for k, v in transition.reward_terms.items()},
        raw_action=distribution(window.raw_action),
        clipped_fraction=float(np.mean(np.abs(np.asarray(window.raw_action))[active] >= 1.)))
    inputs = np.asarray(window.critic_inputs)[active]
    report['critic_feature_scales'] = {row['name']:distribution(
        np.abs(inputs[:, row['start']:row['end']])) for row in layout['fields']}
    write_json_unique(args.output_dir/'forward_diagnostic.json', report, guard.budget)
    guard.check()
    print('Frozen forward and reward calibration complete; computing gradients', flush=True)
    # Four lanes for bounded reverse-mode verification, preserving actual64 steps.
    small_state = slice_environment(state, 0, 4)
    small_pool = init_pool(small_state, keys[:4])
    small = session._replace(pool=small_pool)
    grad_fn = make_actor_gradient(parameters['robot'], auxiliary, **options)
    (gradient, windows, metrics), gradient_s = timed(actor_gradient_window,
        small, proposals[:, :4], grad_fn, microbatch=4)
    report['actor_gradient'] = dict(metrics, **gradient_summary(gradient),
        first_including_compile_s=gradient_s)
    write_json_unique(args.output_dir/'gradient_diagnostic.json', report, guard.budget)
    guard.check()
    (split_gradient, _, _), split_s = timed(actor_gradient_window,
        small, proposals[:, :4], grad_fn, microbatch=2)
    difference = tree_difference(gradient, split_gradient)
    report['actor_microbatch'] = dict(max_abs=difference, first_including_compile_s=split_s,
        relative_to_max=difference/max(report['actor_gradient']['maximum'], 1e-12))
    if difference > 1e-4 + .01*report['actor_gradient']['maximum']:
        raise ValueError('Actor microbatch gradient discrepancy exceeds diagnostic tolerance')
    x, y = critic_training_arrays(windows, critic, lambda_value=cfg['imagination']['lambda'])
    (critic_gradient, critic_loss), critic_s = timed(critic_gradient_batch,
        critic, x, y, microbatch=64)
    report['critic_gradient'] = dict(**gradient_summary(critic_gradient), loss=critic_loss,
        first_including_compile_s=critic_s, samples=len(x), targets=distribution(y))
    guard.check()
    committed = commit_policy_windows(small, windows)
    signature = runtime_signature(cfg, model_references=dict(references, auxiliary=auxiliary_reference),
        geometry_sha256=config_hash(reader.report['geometry']), critic_layout=layout)
    # Release the two reverse-mode executables before independent forward
    # diagnostics; all numerical gradients and frozen weights are retained.
    grad_fn.clear_cache()
    release_cpu_heap()
    if args.extended_validation:
        from .imagination_diagnostics import check_continuation_and_direction
        report['extended'] = check_continuation_and_direction(small, gradient, windows,
            proposals[:, :4], run, robot=parameters['robot'], auxiliary=auxiliary,
            options=options, signature=signature, output_dir=args.output_dir, guard=guard)
    checkpoint_state = dict(learner=committed, frozen_robot=parameters['robot'], frozen_auxiliary=auxiliary)
    reference = save_checkpoint(args.output_dir/'learner_no_update.json', checkpoint_state,
        signature=signature, budget=guard.budget,
        metadata=dict(actor_updates=0, critic_updates=0, source_commit=report['source_commit'],
            config_sha256=config_hash(cfg), model_references=dict(references, auxiliary=auxiliary_reference),
            teacher_transitions_used_for_learning=0, elapsed_s=guard.report()['wall_s']))
    restored = restore_checkpoint(reference, checkpoint_state, signature=signature)['learner']
    replay_a, _ = timed(run, committed.pool.environment, committed.pool.exploration_rng, proposals[:, :4])
    replay_b, _ = timed(run, restored.pool.environment, restored.pool.exploration_rng, proposals[:, :4])
    replay_difference = tree_difference(replay_a, replay_b)
    if replay_difference != 0.:
        raise ValueError('Same graph/state/RNG restore differs')
    report['resume'] = dict(checkpoint=reference, max_abs=replay_difference,
        state_sha256=numeric_tree_digest(committed.pool), optimizer_updates=0)
    report['frozen_after_sha256'] = numeric_tree_digest(frozen)
    if report['frozen_after_sha256'] != frozen_digest:
        raise ValueError('A frozen parameter or optimizer tree changed')
    report.update(status='NO_UPDATE_DIAGNOSTIC_COMPLETE', actual_actor_updates=0,
        actual_critic_updates=0, actual_world_updates=0, task_qualification=False,
        missing_scope=['full1024 throughput', 'multi-stage long-task training',
                       'physical-policy validation after learning'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--validate-only', action='store_true', required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--gpu-uuid', required=True)
    parser.add_argument('--seed', type=int, default=2026110919)
    parser.add_argument('--extended-validation', action='store_true')
    args = parser.parse_args()
    cfg = load_config()
    validate_no_update_contract(cfg)
    with RunGuard(cfg, args.gpu_uuid, args.output_dir, 1800.) as guard:
        args.output_dir.mkdir(parents=True, exist_ok=False)
        sources = sorted(Path(__file__).parent.glob('*.py'))
        report = dict(schema='wmj_v1_imagination_no_update', status='INCOMPLETE',
            training_version='WMJ-V1', config_sha256=config_hash(cfg),
            source_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip(),
            source_sha256={p.name:file_hash(p) for p in sources}, gpu_uuid=args.gpu_uuid,
            arguments={k:str(v) if isinstance(v, Path) else v for k,v in vars(args).items()},
            actual_actor_updates=0, actual_critic_updates=0, actual_world_updates=0)
        write_json_unique(args.output_dir/'implementation.json',
            dict(report=report, source={p.name:p.read_text() for p in sources}), guard.budget)
        write_json_unique(args.output_dir/'config_snapshot.json', dict(config=cfg,
            protocol=(repository_root()/cfg['training_protocol']['path']).read_text()), guard.budget)
        try:
            if jax.default_backend() != 'gpu' or len(jax.devices()) != 1:
                raise ValueError('Exactly one CUDA device required')
            validate(cfg, args, guard, report)
        except Exception as exc:
            report['error'] = repr(exc)
            raise
        finally:
            report['resources'] = guard.report()
            write_json_unique(args.output_dir/'result.json', report, guard.budget)


if __name__ == '__main__':
    main()
